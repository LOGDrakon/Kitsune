        useCase(CHAT_ID, listOf(message(1)))

        coVerify { loreEntryRepository.upsert(withArg { entry -> assertEquals(LoreEntryType.CHARACTER, entry.entryType) }) }
    }

    @Test
    fun `skips entries with a blank name`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
