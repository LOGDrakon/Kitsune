private const val CHAT_ID = "chat-1"

private fun message(index: Int, content: String = "message $index") = MessageEntity(
    id = "msg-$index",
    chatId = CHAT_ID,
    role = if (index % 2 == 0) MessageRole.USER else MessageRole.ASSISTANT,
    content = content,
    imageAttachmentPath = null,
    tokenCount = null,
    createdAt = index.toLong()
)

private fun chatEntity(storyTimeAnchor: String = "") = ChatEntity(
    id = CHAT_ID,
    universeId = null,
    personaId = "persona-1",
    title = "Test chat",
    mode = ChatMode.CHAT,
    storyTimeAnchor = storyTimeAnchor,
    createdAt = 0L,
    updatedAt = 0L
)

class ExtractLoreEntriesUseCaseTest {

    private val loreEntryRepository = mockk<LoreEntryRepository>()
    private val chatRepository = mockk<ChatRepository> {
        coEvery { getById(CHAT_ID) } returns chatEntity()
    }
    private val chatCompletionRepository = mockk<ChatCompletionRepository>()
    private val llmModelResolver = mockk<LlmModelResolver> {
        coEvery { resolve(any()) } returns "gpt-4.1"
    }
    private val indexMemoryFragmentUseCase = mockk<IndexMemoryFragmentUseCase>()

    private val useCase = ExtractLoreEntriesUseCase(
        loreEntryRepository,
        chatRepository,
        chatCompletionRepository,
        llmModelResolver,
        indexMemoryFragmentUseCase
    )

    private fun completion(content: String) =
        Result.success(ChatCompletionResult(content = content, usage = null, modelUsed = "gpt-5-mini"))

    @Test
    fun `does nothing when there are no messages`() = runTest {
        useCase(CHAT_ID, emptyList())

        coVerify(exactly = 0) { loreEntryRepository.getByChat(any()) }
        coVerify(exactly = 0) { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) }
    }

    @Test
    fun `creates a new lore entry from the AI response and indexes it`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { loreEntryRepository.findByChatAndNameOrAlias(CHAT_ID, any()) } returns null
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "Aria", "entryType": "CHARACTER", "summary": "A mercenary.", "content": "Tall, silver hair, cold but loyal."}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify {
            loreEntryRepository.upsert(
                withArg { entry ->
                    assertEquals("Aria", entry.name)
                    assertEquals(LoreEntryType.CHARACTER, entry.entryType)
                    assertEquals("A mercenary.", entry.summary)
                    assertTrue(entry.isAutoGenerated)
                    assertEquals(1, entry.version)
                    assertEquals(CHAT_ID, entry.chatId)
                }
            )
        }
        coVerify { indexMemoryFragmentUseCase(CHAT_ID, MemoryFragmentSource.LORE_ENTRY, any(), any()) }
    }

    @Test
    fun `sets occurredAt on a newly created EVENT entry`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { loreEntryRepository.findByChatAndNameOrAlias(CHAT_ID, any()) } returns null
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "The docks confrontation", "entryType": "EVENT", "summary": "A tense standoff.", "content": "Details.", "occurredAt": "Early winter, three days before the wedding."}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify {
            loreEntryRepository.upsert(
                withArg { entry ->
                    assertEquals(LoreEntryType.EVENT, entry.entryType)
                    assertEquals("Early winter, three days before the wedding.", entry.occurredAt)
                }
            )
        }
    }

    @Test
    fun `never overwrites occurredAt on an existing entry re-matched by a later batch`() = runTest {
        val existing = LoreEntryEntity(
            id = "event-1",
            chatId = CHAT_ID,
            entryType = LoreEntryType.EVENT,
            name = "The docks confrontation",
            summary = "old summary",
            content = "old content",
            isAutoGenerated = true,
            occurredAt = "Early winter, three days before the wedding.",
            version = 1,
            createdAt = 10L,
            updatedAt = 10L
        )
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns listOf(existing)
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "The docks confrontation", "entryType": "EVENT", "summary": "Enriched summary.", "content": "More detail.", "occurredAt": "A completely different, later time."}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify {
            loreEntryRepository.upsert(
                withArg { entry ->
                    assertEquals("Early winter, three days before the wedding.", entry.occurredAt)
                    assertEquals("Enriched summary.", entry.summary)
                }
            )
        }
    }

    @Test
    fun `updates an existing entry by case-insensitive name match instead of duplicating`() = runTest {
        val existing = LoreEntryEntity(
            id = "entry-1",
            chatId = CHAT_ID,
            entryType = LoreEntryType.CHARACTER,
            name = "aria",
            summary = "old summary",
            content = "old content",
            isAutoGenerated = true,
            version = 2,
            createdAt = 10L,
            updatedAt = 10L
        )
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns listOf(existing)
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "Aria", "entryType": "CHARACTER", "summary": "New info.", "content": "New content."}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify {
            loreEntryRepository.upsert(
                withArg { entry ->
                    assertEquals("entry-1", entry.id)
                    assertEquals(3, entry.version)
                    assertEquals("New info.", entry.summary)
                    assertEquals(10L, entry.createdAt)
                }
            )
        }
    }

    @Test
    fun `falls back to CHARACTER for an unrecognized entry type`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { loreEntryRepository.findByChatAndNameOrAlias(CHAT_ID, any()) } returns null
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "Aria", "entryType": "NOT_A_REAL_TYPE", "summary": "s", "content": "c"}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
