        )

        useCase(CHAT_ID, listOf(message(1)))

        coVerify(exactly = 0) { loreEntryRepository.upsert(any()) }
    }

    @Test
    fun `does nothing when the AI returns an empty entries array`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion("""{"entries": []}""")

        useCase(CHAT_ID, listOf(message(1)))

        coVerify(exactly = 0) { loreEntryRepository.upsert(any()) }
    }

    @Test
    fun `never throws and upserts nothing when the completion call fails`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns
            Result.failure(IllegalStateException("network down"))

        useCase(CHAT_ID, listOf(message(1)))

        coVerify(exactly = 0) { loreEntryRepository.upsert(any()) }
    }

    @Test
    fun `uses the model returned by the LLM resolver`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion("""{"entries": []}""")

        useCase(CHAT_ID, listOf(message(1)))

        coVerify { llmModelResolver.resolve(any()) }
        coVerify { chatCompletionRepository.complete("gpt-4.1", any(), any(), any(), any(), any(), any(), any(), any()) }
    }

    @Test
    fun `persists a returned currentStoryTime onto the chat`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [], "currentStoryTime": "Early winter, three days after the docks confrontation, mid-morning."}"""
        )
        coEvery { chatRepository.upsert(any()) } returns Unit

        useCase(CHAT_ID, listOf(message(1)))

        coVerify {
            chatRepository.upsert(
                withArg { chat ->
                    assertEquals("Early winter, three days after the docks confrontation, mid-morning.", chat.storyTimeAnchor)
                    assertTrue(chat.updatedAt > 0L)
                }
            )
        }
    }

    @Test
    fun `leaves the existing story time anchor untouched when the AI reports no time signal`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [], "currentStoryTime": null}"""
        )

        useCase(CHAT_ID, listOf(message(1)))

        coVerify(exactly = 0) { chatRepository.upsert(any()) }
    }

    @Test
    fun `includes the existing story time anchor in the prompt sent to the classifier`() = runTest {
        coEvery { chatRepository.getById(CHAT_ID) } returns chatEntity(storyTimeAnchor = "Late summer, the evening after the festival.")
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        val messagesSlot = slot<List<ChatTurn>>()
        coEvery {
            chatCompletionRepository.complete(any(), any(), capture(messagesSlot), any(), any(), any(), any(), any(), any())
        } returns completion("""{"entries": []}""")

        useCase(CHAT_ID, listOf(message(1)))

        assertTrue(messagesSlot.captured.single().content.contains("Late summer, the evening after the festival."))
    }

    @Test
    fun `still upserts lore entries even when the story time upsert fails`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { loreEntryRepository.findByChatAndNameOrAlias(CHAT_ID, any()) } returns null
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "Aria", "entryType": "CHARACTER", "summary": "A mercenary.", "content": "Tall, silver hair."}], "currentStoryTime": "Late summer."}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }
        coEvery { chatRepository.upsert(any()) } throws IllegalStateException("db closed")

        useCase(CHAT_ID, listOf(message(1)))

        coVerify { loreEntryRepository.upsert(withArg { entry -> assertEquals("Aria", entry.name) }) }
    }

    @Test
    fun `records the aliases reported for a new entity`() = runTest {
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns emptyList()
        coEvery { loreEntryRepository.findByChatAndNameOrAlias(CHAT_ID, any()) } returns null
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "Aria", "entryType": "CHARACTER", "summary": "A mercenary.", "content": "Tall.", "aliases": ["la mercenaire", "la Louve", "Aria"]}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify {
            loreEntryRepository.upsert(withArg { entry ->
                // The entity's own name must never be echoed back into its alias list.
                assertEquals(listOf("la mercenaire", "la Louve"), entry.aliases)
            })
        }
    }

    @Test
    fun `merges into the existing sheet when the entity is only known by an alias`() = runTest {
        val existing = LoreEntryEntity(
            id = "entry-1",
            chatId = CHAT_ID,
            entryType = LoreEntryType.CHARACTER,
            name = "Aria",
            summary = "A mercenary.",
            content = "Tall, silver hair, carries a silver sword.",
            isAutoGenerated = true,
            aliases = listOf("la mercenaire"),
            version = 3,
            createdAt = 10L,
            updatedAt = 10L
        )
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns listOf(existing)
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "la mercenaire", "entryType": "CHARACTER", "summary": "Une mercenaire.", "content": "Short."}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify(exactly = 1) {
            loreEntryRepository.upsert(withArg { entry ->
                assertEquals("entry-1", entry.id)
                assertEquals("Aria", entry.name)
                assertEquals(4, entry.version)
                // A merge must never shrink a sheet: the longer content wins over the newer one.
                assertEquals("Tall, silver hair, carries a silver sword.", entry.content)
            })
        }
        coVerify(exactly = 0) { loreEntryRepository.findByChatAndNameOrAlias(any(), any()) }
    }

    @Test
    fun `follows an explicit sameAs link instead of creating a duplicate`() = runTest {
        val existing = LoreEntryEntity(
            id = "entry-1",
            chatId = CHAT_ID,
            entryType = LoreEntryType.CHARACTER,
            name = "Aria",
            summary = "A mercenary.",
            content = "Tall.",
            isAutoGenerated = true,
            version = 1,
            createdAt = 10L,
            updatedAt = 10L
        )
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns listOf(existing)
        coEvery { chatCompletionRepository.complete(any(), any(), any(), any(), any(), any(), any(), any(), any()) } returns completion(
            """{"entries": [{"name": "la Louve", "entryType": "CHARACTER", "summary": "Une mercenaire.", "content": "Longer content here.", "sameAs": "Aria"}]}"""
        )
        coEvery { loreEntryRepository.upsert(any()) } returns Unit
        coJustRun { indexMemoryFragmentUseCase(any(), any(), any(), any()) }

        useCase(CHAT_ID, listOf(message(1)))

        coVerify(exactly = 1) {
            loreEntryRepository.upsert(withArg { entry ->
                assertEquals("entry-1", entry.id)
                assertEquals("Aria", entry.name)
                // The name it was referred to under becomes an alias, so the link sticks.
                assertTrue(entry.aliases.contains("la Louve"))
            })
        }
    }

    @Test
    fun `feeds known aliases back into the prompt roster`() = runTest {
        coEvery { chatRepository.getById(CHAT_ID) } returns chatEntity()
        coEvery { loreEntryRepository.getByChat(CHAT_ID) } returns listOf(
            LoreEntryEntity(
                id = "entry-1",
                chatId = CHAT_ID,
                entryType = LoreEntryType.CHARACTER,
                name = "Aria",
                summary = "A mercenary.",
                content = "Tall.",
                aliases = listOf("la mercenaire", "la Louve"),
                createdAt = 10L,
                updatedAt = 10L
            )
        )
        val messagesSlot = slot<List<ChatTurn>>()
        coEvery {
            chatCompletionRepository.complete(any(), any(), capture(messagesSlot), any(), any(), any(), any(), any(), any())
        } returns completion("""{"entries": []}""")

        useCase(CHAT_ID, listOf(message(1)))

        assertTrue(messagesSlot.captured.single().content.contains("Aria [aka: la mercenaire, la Louve]"))
    }
}
